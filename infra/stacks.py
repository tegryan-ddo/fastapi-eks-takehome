"""The four stacks. Names and secret paths match docs/operations.md."""

import aws_cdk as cdk
from aws_cdk import aws_codebuild as codebuild
from aws_cdk import aws_codeconnections as codeconnections
from aws_cdk import aws_ec2 as ec2
from aws_cdk import aws_ecr as ecr
from aws_cdk import aws_iam as iam
from aws_cdk import aws_logs as logs
from aws_cdk import aws_rds as rds
from aws_cdk import aws_secretsmanager as secretsmanager
from constructs import Construct

# Amazon Linux 2023 image; its Python 3.13 runtime matches the application image.
BUILD_IMAGE = codebuild.LinuxBuildImage.from_code_build_image_id("aws/codebuild/amazonlinux-x86_64-standard:6.0")
POSTGRES_VERSION = rds.PostgresEngineVersion.of("17.11", "17")  # latest offered by RDS, 2026-10-28
RUNTIME_SECRET_NAME = "/mobile-api/staging/runtime"  # written by scripts/load_secrets.py
MASTER_SECRET_NAME = "/mobile-api/staging/rds-master"  # generated by RDS, never used by the app


class FoundationStack(cdk.Stack):
    def __init__(self, scope: Construct, id: str, **kwargs):
        super().__init__(scope, id, **kwargs)

        self.repository = ecr.Repository(
            self, "Repository",
            repository_name="mobile-api",
            image_tag_mutability=ecr.TagMutability.IMMUTABLE,
            image_scan_on_push=True,
            removal_policy=cdk.RemovalPolicy.RETAIN,
            lifecycle_rules=[ecr.LifecycleRule(description="Keep the last 30 images", max_image_count=30)],
        )

        # Created PENDING; a person completes the GitHub handshake in the console.
        connection = codeconnections.CfnConnection(
            self, "GitHubConnection", connection_name="fastapi-eks-takehome", provider_type="GitHub",
        )
        self.connection_arn = connection.attr_connection_arn

        cdk.CfnOutput(self, "RepositoryUri", value=self.repository.repository_uri)
        cdk.CfnOutput(self, "ConnectionArn", value=self.connection_arn)
        cdk.CfnOutput(
            self, "ConnectionConsoleUrl",
            value=f"https://{self.region}.console.aws.amazon.com/codesuite/settings/connections?region={self.region}",
            description="Complete the pending GitHub connection here",
        )


class DatabaseStack(cdk.Stack):
    """A VPC and an RDS PostgreSQL instance standing in for the external database.

    Context eksWorkloadSecurityGroupId, when supplied, is also allowed to reach
    port 5432. Database tuning is out of scope.
    """

    def __init__(self, scope: Construct, id: str, **kwargs):
        super().__init__(scope, id, **kwargs)

        self.vpc = ec2.Vpc(
            self, "Vpc",
            vpc_name="mobile-api",
            ip_addresses=ec2.IpAddresses.cidr("10.60.0.0/16"),
            max_azs=2,
            nat_gateways=1,  # the runners' only route to PyPI, GitHub, ECR and AWS APIs
            subnet_configuration=[
                ec2.SubnetConfiguration(name="public", subnet_type=ec2.SubnetType.PUBLIC, cidr_mask=24),
                ec2.SubnetConfiguration(name="runners", subnet_type=ec2.SubnetType.PRIVATE_WITH_EGRESS, cidr_mask=24),
                ec2.SubnetConfiguration(name="database", subnet_type=ec2.SubnetType.PRIVATE_ISOLATED, cidr_mask=24),
                # EKS nodes and pods; a /20 per AZ because the VPC CNI gives every pod an IP.
                ec2.SubnetConfiguration(name="nodes", subnet_type=ec2.SubnetType.PRIVATE_WITH_EGRESS, cidr_mask=20),
            ],
        )
        # Tags the EKS load-balancer controller uses to pick subnets for ALBs.
        for subnet in self.vpc.public_subnets:
            cdk.Tags.of(subnet).add("kubernetes.io/role/elb", "1")
        for subnet in self.vpc.select_subnets(subnet_group_name="nodes").subnets:
            cdk.Tags.of(subnet).add("kubernetes.io/role/internal-elb", "1")

        self.runner_security_group = ec2.SecurityGroup(
            self, "RunnerSecurityGroup", vpc=self.vpc, description="CodeBuild runners that reach RDS",
        )
        self.database_security_group = ec2.SecurityGroup(
            self, "DatabaseSecurityGroup", vpc=self.vpc, description="RDS mobile-api-staging", allow_all_outbound=False,
        )
        self.database_security_group.add_ingress_rule(self.runner_security_group, ec2.Port.tcp(5432), "VPC runners")
        # The EKS stack adds the cluster's own rule; this covers a cluster created elsewhere.
        eks_security_group_id = self.node.try_get_context("eksWorkloadSecurityGroupId")
        if eks_security_group_id:
            eks_workloads = ec2.SecurityGroup.from_security_group_id(self, "EksWorkloads", eks_security_group_id)
            self.database_security_group.add_ingress_rule(eks_workloads, ec2.Port.tcp(5432), "EKS workloads")
        database_security_group = self.database_security_group

        engine = rds.DatabaseInstanceEngine.postgres(version=POSTGRES_VERSION)
        parameters = rds.ParameterGroup(
            self, "ParameterGroup", engine=engine,
            description="mobile-api: TLS required",
            parameters={"rds.force_ssl": "1"},
        )
        database = rds.DatabaseInstance(
            self, "Database",
            instance_identifier="mobile-api-staging",
            engine=engine,
            instance_type=ec2.InstanceType.of(ec2.InstanceClass.BURSTABLE4_GRAVITON, ec2.InstanceSize.MICRO),
            vpc=self.vpc,
            vpc_subnets=ec2.SubnetSelection(subnet_group_name="database"),
            security_groups=[database_security_group],
            credentials=rds.Credentials.from_generated_secret("postgres_admin", secret_name=MASTER_SECRET_NAME),
            database_name="mobileapi",
            parameter_group=parameters,
            ca_certificate=rds.CaCertificate.RDS_CA_RSA2048_G1,
            allocated_storage=20,
            storage_type=rds.StorageType.GP3,
            storage_encrypted=True,
            publicly_accessible=False,
            multi_az=False,
            backup_retention=cdk.Duration.days(1),
            cloudwatch_logs_exports=["postgresql"],
            removal_policy=cdk.RemovalPolicy.SNAPSHOT,
        )
        self.master_secret = database.secret

        cdk.CfnOutput(self, "VpcId", value=self.vpc.vpc_id)
        cdk.CfnOutput(self, "DatabaseEndpoint", value=database.db_instance_endpoint_address)
        cdk.CfnOutput(self, "DatabaseSecurityGroupId", value=database_security_group.security_group_id)
        cdk.CfnOutput(self, "RunnerSecurityGroupId", value=self.runner_security_group.security_group_id)
        cdk.CfnOutput(self, "MasterSecretName", value=MASTER_SECRET_NAME)


def github_project(scope, id, *, name, owner, repo, buildspec, connection_arn, privileged=False,
                   timeout_minutes=20, webhook_filters=None, **kwargs) -> codebuild.Project:
    """A CodeBuild project reading this repository through CodeConnections."""
    project = codebuild.Project(
        scope, id,
        project_name=name,
        source=codebuild.Source.git_hub(
            owner=owner, repo=repo,
            webhook=webhook_filters is not None, webhook_filters=webhook_filters,
        ),
        build_spec=codebuild.BuildSpec.from_source_filename(buildspec),
        environment=codebuild.BuildEnvironment(
            build_image=BUILD_IMAGE, compute_type=codebuild.ComputeType.SMALL, privileged=privileged,
        ),
        timeout=cdk.Duration.minutes(timeout_minutes),
        concurrent_build_limit=1,
        logging=codebuild.LoggingOptions(cloud_watch=codebuild.CloudWatchLoggingOptions(
            log_group=logs.LogGroup(scope, f"{id}Logs", retention=logs.RetentionDays.ONE_MONTH),
        )),
        **kwargs,
    )
    # The L2 construct has no CodeConnections option; set the source auth directly.
    project.node.default_child.add_property_override(
        "Source.Auth", {"Type": "CODECONNECTIONS", "Resource": connection_arn},
    )
    # CodeBuild checks, as the project role, that it can read the connection
    # while creating the project. The grant lives in its own policy so the
    # project can depend on it; the role's default policy references the
    # project, so depending on that would be a cycle.
    connection_access = iam.Policy(
        scope, f"{id}ConnectionAccess", roles=[project.role],
        statements=[iam.PolicyStatement(
            actions=[
                "codeconnections:GetConnection", "codeconnections:GetConnectionToken",
                "codestar-connections:GetConnection", "codestar-connections:GetConnectionToken",
            ],
            resources=[connection_arn],
        )],
    )
    project.node.default_child.add_dependency(connection_access.node.default_child)
    return project


class BuildStack(cdk.Stack):
    def __init__(self, scope: Construct, id: str, *, github_owner, github_repo, connection_arn,
                 repository: ecr.IRepository, **kwargs):
        super().__init__(scope, id, **kwargs)
        source = dict(owner=github_owner, repo=github_repo, connection_arn=connection_arn)

        # Pull requests: tests and secret scan only. No Docker, no registry access.
        github_project(
            self, "Validate", name="mobile-api-validate", buildspec="buildspecs/validate.yml",
            webhook_filters=[codebuild.FilterGroup.in_event_of(
                codebuild.EventAction.PULL_REQUEST_CREATED,
                codebuild.EventAction.PULL_REQUEST_UPDATED,
                codebuild.EventAction.PULL_REQUEST_REOPENED,
            )],
            **source,
        )

        # Pushes to main: full verification, image build, push to ECR by commit SHA.
        build = github_project(
            self, "Build", name="mobile-api-build", buildspec="buildspecs/build.yml",
            privileged=True,  # Docker
            timeout_minutes=40,
            webhook_filters=[codebuild.FilterGroup.in_event_of(codebuild.EventAction.PUSH).and_branch_is("main")],
            environment_variables={
                "ECR_REPOSITORY_URI": codebuild.BuildEnvironmentVariable(value=repository.repository_uri),
            },
            cache=codebuild.Cache.local(codebuild.LocalCacheMode.DOCKER_LAYER, codebuild.LocalCacheMode.SOURCE),
            **source,
        )
        repository.grant_pull_push(build)
        build.add_to_role_policy(iam.PolicyStatement(
            actions=["ecr:DescribeImages"], resources=[repository.repository_arn],
        ))


class IntegrationStack(cdk.Stack):
    """Projects that run inside the VPC, started by hand (no webhooks)."""

    def __init__(self, scope: Construct, id: str, *, github_owner, github_repo, connection_arn,
                 vpc: ec2.IVpc, runner_security_group: ec2.ISecurityGroup,
                 master_secret: secretsmanager.ISecret, **kwargs):
        super().__init__(scope, id, **kwargs)
        in_vpc = dict(
            owner=github_owner, repo=github_repo, connection_arn=connection_arn,
            vpc=vpc, subnet_selection=ec2.SubnetSelection(subnet_group_name="runners"),
            security_groups=[runner_security_group],
        )
        runtime_secret_arn = self.format_arn(
            service="secretsmanager", resource="secret",
            resource_name=f"{RUNTIME_SECRET_NAME}-*", arn_format=cdk.ArnFormat.COLON_RESOURCE_NAME,
        )
        read_runtime_secret = iam.PolicyStatement(
            actions=["secretsmanager:GetSecretValue"], resources=[runtime_secret_arn],
        )

        # One-off: creates the application role from the master account.
        db_admin = github_project(
            self, "DbAdmin", name="mobile-api-db-admin", buildspec="buildspecs/db-bootstrap.yml",
            timeout_minutes=10, **in_vpc,
        )
        master_secret.grant_read(db_admin)
        db_admin.add_to_role_policy(read_runtime_secret)

        # Migrations and integration tests against RDS, as the application role.
        integration = github_project(
            self, "Integration", name="mobile-api-integration", buildspec="buildspecs/integration.yml",
            **in_vpc,
        )
        integration.add_to_role_policy(read_runtime_secret)
